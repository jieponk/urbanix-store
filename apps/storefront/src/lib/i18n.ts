/**
 * Bahasa tampilan toko: Indonesia (bawaan) & Inggris.
 *
 * Teks ditulis dalam Bahasa Indonesia seperti biasa lalu dibungkus `t('...')`.
 * Kamus EN di bawah memetakan teks Indonesia → Inggris. Teks yang belum ada di kamus
 * tetap tampil dalam Bahasa Indonesia (tidak pernah kosong/rusak).
 * Variabel: t('Hemat {n}%', { n: 8 }).
 *
 * Isi dari database (nama/deskripsi produk, artikel, voucher) diterjemahkan di backend (DeepL),
 * bukan di sini — lihat apps/backend/store/content_i18n.py.
 */
export type Lang = 'id' | 'en';
export const LANG_COOKIE = 'urbanix-lang';
export const LANGS: { code: Lang; label: string; short: string }[] = [
  { code: 'id', label: 'Bahasa Indonesia', short: 'ID' },
  { code: 'en', label: 'English', short: 'EN' },
];

/** Locale untuk tanggal & angka. Harga tetap Rupiah. */
export const dateLocale = (lang: Lang) => (lang === 'en' ? 'en-US' : 'id-ID');

export type Vars = Record<string, string | number>;
export type T = (text: string, vars?: Vars) => string;

export function translator(lang: Lang): T {
  return (text, vars) => {
    let out = lang === 'en' ? EN[text] ?? text : text;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    return out;
  };
}

